// Command gen-eth-fixtures converts the Ethereum light-client fixtures of
// cosmos/solidity-ibc-eureka (packages/ethereum/light-client/src/test_utils/
// fixtures) into Gno test data for gno.land/p/aib/ibc/lightclient/ethereum.
//
// Each fixture records a real Ethereum devnet: an initial client and
// consensus state, then the relayer transactions that updated the client and
// relayed packets with storage proofs. The output reproduces those steps in
// order as Gno literals.
//
// Usage: gen-eth-fixtures <fixture.json> <FuncName> <out.gno>
package main

import (
	"bytes"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"strconv"
	"strings"

	"google.golang.org/protobuf/encoding/protowire"
)

func main() {
	if len(os.Args) != 4 {
		fmt.Fprintln(os.Stderr, "usage: gen-eth-fixtures <fixture.json> <FuncName> <out.gno>")
		os.Exit(2)
	}
	src, err := os.ReadFile(os.Args[1])
	check(err)
	out, err := generate(src, os.Args[2], os.Args[1])
	check(err)
	check(os.WriteFile(os.Args[3], out, 0o644))
}

func check(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func decodeJSON(b []byte) (any, error) {
	d := json.NewDecoder(bytes.NewReader(b))
	d.UseNumber()
	var v any
	return v, d.Decode(&v)
}

func generate(src []byte, funcName, srcName string) ([]byte, error) {
	root, err := decodeJSON(src)
	if err != nil {
		return nil, err
	}
	steps := obj(root)["steps"].([]any)

	var w bytes.Buffer
	fmt.Fprintf(&w, "// Code generated by cmd/gen-eth-fixtures from %s\n", baseName(srcName))
	fmt.Fprintf(&w, "// (cosmos/solidity-ibc-eureka, MIT licensed). DO NOT EDIT.\n\n")
	fmt.Fprintf(&w, "package ethereum\n\nimport \"gno.land/p/aib/ibc/types/v0\"\n\n")
	fmt.Fprintf(&w, "func %s() fixture {\n\treturn fixture{\n", funcName)

	initial := obj(obj(steps[0])["data"])
	fmt.Fprintf(&w, "clientState: %s,\n", clientState(obj(initial["client_state"])))
	fmt.Fprintf(&w, "consensusState: %s,\n", consensusState(obj(initial["consensus_state"])))
	fmt.Fprintf(&w, "steps: []fixtureStep{\n")
	for _, s := range steps[1:] {
		data := obj(obj(s)["data"])
		body, err := hex.DecodeString(str(data["relayer_tx_body"]))
		if err != nil {
			return nil, err
		}
		for _, anyBz := range field(body, 1) {
			if err := step(&w, anyBz); err != nil {
				return nil, err
			}
		}
	}
	fmt.Fprintf(&w, "},\n}\n}\n")
	return format.Source(w.Bytes())
}

func step(w *bytes.Buffer, anyBz []byte) error {
	url := string(one(anyBz, 1))
	msg := one(anyBz, 2)
	switch url {
	case "/ibc.core.client.v1.MsgUpdateClient":
		clientMsg := one(one(msg, 2), 2) // Any.value: wasm ClientMessage
		v, err := decodeJSON(one(clientMsg, 1))
		if err != nil {
			return err
		}
		fmt.Fprintf(w, "{update: %s},\n", header(obj(v)))
	case "/ibc.core.channel.v2.MsgRecvPacket":
		// packet=1 proof_commitment=2 proof_height=3
		p := packet(one(msg, 1))
		fmt.Fprintf(w, "{proof: &fixtureProof{height: %s, proof: %s, packet: %s}},\n",
			height(one(msg, 3)), membershipProof(one(msg, 2)), p)
	case "/ibc.core.channel.v2.MsgAcknowledgement":
		// packet=1 acknowledgement=2 proof_acked=3 proof_height=4
		p := packet(one(msg, 1))
		fmt.Fprintf(w, "{proof: &fixtureProof{height: %s, proof: %s, packet: %s, ack: %s}},\n",
			height(one(msg, 4)), membershipProof(one(msg, 3)), p, ack(one(msg, 2)))
	case "/ibc.core.channel.v2.MsgTimeout":
		// packet=1 proof_unreceived=2 proof_height=3
		p := packet(one(msg, 1))
		fmt.Fprintf(w, "{proof: &fixtureProof{height: %s, proof: %s, packet: %s, absent: true}},\n",
			height(one(msg, 3)), membershipProof(one(msg, 2)), p)
	default:
		return fmt.Errorf("unexpected message %s", url)
	}
	return nil
}

// --- protobuf helpers ---

func fields(b []byte) map[protowire.Number][][]byte {
	m := map[protowire.Number][][]byte{}
	for len(b) > 0 {
		num, typ, n := protowire.ConsumeTag(b)
		if n < 0 {
			panic("bad tag")
		}
		b = b[n:]
		switch typ {
		case protowire.BytesType:
			v, n := protowire.ConsumeBytes(b)
			m[num] = append(m[num], v)
			b = b[n:]
		case protowire.VarintType:
			v, n := protowire.ConsumeVarint(b)
			m[num] = append(m[num], protowire.AppendVarint(nil, v))
			b = b[n:]
		default:
			n := protowire.ConsumeFieldValue(num, typ, b)
			b = b[n:]
		}
	}
	return m
}

func field(b []byte, n protowire.Number) [][]byte { return fields(b)[n] }

func one(b []byte, n protowire.Number) []byte {
	f := field(b, n)
	if len(f) == 0 {
		return nil
	}
	return f[0]
}

func varint(b []byte, n protowire.Number) uint64 {
	f := one(b, n)
	if f == nil {
		return 0
	}
	v, _ := protowire.ConsumeVarint(f)
	return v
}

func packet(b []byte) string {
	var payloads []string
	for _, p := range field(b, 5) {
		payloads = append(payloads, fmt.Sprintf(
			"{SourcePort: %q, DestinationPort: %q, Version: %q, Encoding: %q, Value: h(%q)}",
			one(p, 1), one(p, 2), one(p, 3), one(p, 4), hex.EncodeToString(one(p, 5))))
	}
	return fmt.Sprintf("types.Packet{Sequence: %d, SourceClient: %q, DestinationClient: %q, TimeoutTimestamp: %d, Payloads: []types.Payload{%s}}",
		varint(b, 1), one(b, 2), one(b, 3), varint(b, 4), strings.Join(payloads, ", "))
}

func ack(b []byte) string {
	var acks []string
	for _, a := range field(b, 1) {
		acks = append(acks, fmt.Sprintf("h(%q)", hex.EncodeToString(a)))
	}
	return fmt.Sprintf("&types.Acknowledgement{AppAcknowledgements: [][]byte{%s}}", strings.Join(acks, ", "))
}

func height(b []byte) string {
	return fmt.Sprintf("types.NewHeight(%d, %d)", varint(b, 1), varint(b, 2))
}

// --- JSON helpers ---

func obj(v any) map[string]any { return v.(map[string]any) }

func str(v any) string { return v.(string) }

func u64(v any) uint64 {
	var s string
	switch t := v.(type) {
	case json.Number:
		s = t.String()
	case string:
		s = t
	default:
		panic(fmt.Sprintf("not a number: %T %v", v, v))
	}
	n, err := strconv.ParseUint(s, 0, 64)
	if err != nil {
		panic(err)
	}
	return n
}

func hexOf(v any) string { return strings.TrimPrefix(str(v), "0x") }

func b(v any) string { return fmt.Sprintf("h(%q)", hexOf(v)) }

func bs(v any) string {
	var items []string
	for _, x := range v.([]any) {
		items = append(items, b(x))
	}
	return "[][]byte{" + strings.Join(items, ", ") + "}"
}

func version(v any) string {
	raw, err := hex.DecodeString(hexOf(v))
	if err != nil || len(raw) != 4 {
		panic("bad fork version")
	}
	return fmt.Sprintf("[4]byte{0x%02x, 0x%02x, 0x%02x, 0x%02x}", raw[0], raw[1], raw[2], raw[3])
}

func fork(v any) string {
	f := obj(v)
	return fmt.Sprintf("Fork{Version: %s, Epoch: %d}", version(f["version"]), u64(f["epoch"]))
}

func clientState(cs map[string]any) string {
	fp := obj(cs["fork_parameters"])
	return fmt.Sprintf(`ClientState{
ChainID: %d,
GenesisValidatorsRoot: %s,
MinSyncCommitteeParticipants: %d,
SyncCommitteeSize: %d,
GenesisTime: %d,
GenesisSlot: %d,
ForkParameters: ForkParameters{GenesisForkVersion: %s, GenesisSlot: %d, Altair: %s, Bellatrix: %s, Capella: %s, Deneb: %s, Electra: %s, Fulu: %s},
SecondsPerSlot: %d,
SlotsPerEpoch: %d,
EpochsPerSyncCommitteePeriod: %d,
LatestSlot: %d,
LatestExecutionBlockNumber: %d,
IBCContractAddress: %s,
IBCCommitmentSlot: %s,
}`,
		u64(cs["chain_id"]), b(cs["genesis_validators_root"]), u64(cs["min_sync_committee_participants"]),
		u64(cs["sync_committee_size"]), u64(cs["genesis_time"]), u64(cs["genesis_slot"]),
		version(fp["genesis_fork_version"]), u64(fp["genesis_slot"]), fork(fp["altair"]), fork(fp["bellatrix"]),
		fork(fp["capella"]), fork(fp["deneb"]), fork(fp["electra"]), fork(fp["fulu"]),
		u64(cs["seconds_per_slot"]), u64(cs["slots_per_epoch"]), u64(cs["epochs_per_sync_committee_period"]),
		u64(cs["latest_slot"]), u64(cs["latest_execution_block_number"]),
		b(cs["ibc_contract_address"]), b(cs["ibc_commitment_slot"]))
}

func summary(v any) string {
	s := obj(v)
	return fmt.Sprintf("SummarizedSyncCommittee{PubkeysHash: %s, AggregatePubkey: %s}", b(s["pubkeys_hash"]), b(s["aggregate_pubkey"]))
}

func consensusState(cs map[string]any) string {
	next := "nil"
	if cs["next_sync_committee"] != nil {
		next = "&" + summary(cs["next_sync_committee"])
	}
	return fmt.Sprintf("ConsensusState{Slot: %d, StateRoot: %s, Timestamp: %d, CurrentSyncCommittee: %s, NextSyncCommittee: %s}",
		u64(cs["slot"]), b(cs["state_root"]), u64(cs["timestamp"]), summary(cs["current_sync_committee"]), next)
}

func committee(v any) string {
	c := obj(v)
	return fmt.Sprintf("SyncCommittee{Pubkeys: %s, AggregatePubkey: %s}", bs(c["pubkeys"]), b(c["aggregate_pubkey"]))
}

func lcHeader(v any) string {
	h := obj(v)
	bh := obj(h["beacon"])
	e := obj(h["execution"])
	// base_fee_per_gas is a JSON number or hex/decimal string.
	baseFee := fmt.Sprintf("uint256BE(%q)", fmt.Sprint(e["base_fee_per_gas"]))
	return fmt.Sprintf(`LightClientHeader{
Beacon: BeaconBlockHeader{Slot: %d, ProposerIndex: %d, ParentRoot: %s, StateRoot: %s, BodyRoot: %s},
Execution: ExecutionPayloadHeader{ParentHash: %s, FeeRecipient: %s, StateRoot: %s, ReceiptsRoot: %s, LogsBloom: %s, PrevRandao: %s, BlockNumber: %d, GasLimit: %d, GasUsed: %d, Timestamp: %d, ExtraData: %s, BaseFeePerGas: %s, BlockHash: %s, TransactionsRoot: %s, WithdrawalsRoot: %s, BlobGasUsed: %d, ExcessBlobGas: %d},
ExecutionBranch: %s,
}`,
		u64(bh["slot"]), u64(bh["proposer_index"]), b(bh["parent_root"]), b(bh["state_root"]), b(bh["body_root"]),
		b(e["parent_hash"]), b(e["fee_recipient"]), b(e["state_root"]), b(e["receipts_root"]), b(e["logs_bloom"]),
		b(e["prev_randao"]), u64(e["block_number"]), u64(e["gas_limit"]), u64(e["gas_used"]), u64(e["timestamp"]),
		b(e["extra_data"]), baseFee, b(e["block_hash"]), b(e["transactions_root"]), b(e["withdrawals_root"]),
		u64(e["blob_gas_used"]), u64(e["excess_blob_gas"]),
		bs(h["execution_branch"]))
}

func header(h map[string]any) string {
	active := obj(h["active_sync_committee"])
	isNext := false
	var c any
	if v, ok := active["Next"]; ok {
		isNext, c = true, v
	} else {
		c = active["Current"]
	}
	u := obj(h["consensus_update"])
	next, nextBranch := "nil", "nil"
	if u["next_sync_committee"] != nil {
		next = "&" + committee(u["next_sync_committee"])
		nextBranch = bs(u["next_sync_committee_branch"])
	}
	agg := obj(u["sync_aggregate"])
	return fmt.Sprintf(`&Header{
ActiveSyncCommittee: %s,
ActiveIsNext: %t,
TrustedSlot: %d,
ConsensusUpdate: LightClientUpdate{
AttestedHeader: %s,
NextSyncCommittee: %s,
NextSyncCommitteeBranch: %s,
FinalizedHeader: %s,
FinalityBranch: %s,
SyncAggregate: SyncAggregate{SyncCommitteeBits: %s, SyncCommitteeSignature: %s},
SignatureSlot: %d,
},
}`,
		committee(c), isNext, u64(h["trusted_slot"]),
		lcHeader(u["attested_header"]), next, nextBranch, lcHeader(u["finalized_header"]),
		bs(u["finality_branch"]), b(agg["sync_committee_bits"]), b(agg["sync_committee_signature"]),
		u64(u["signature_slot"]))
}

func membershipProof(raw []byte) string {
	v, err := decodeJSON(raw)
	if err != nil {
		panic(err)
	}
	p := obj(v)
	return fmt.Sprintf("MembershipProof{AccountProof: %s, StorageProof: %s}",
		bs(obj(p["account_proof"])["proof"]), bs(obj(p["storage_proof"])["proof"]))
}

func baseName(p string) string {
	if i := strings.LastIndex(p, "/"); i >= 0 {
		return p[i+1:]
	}
	return p
}
